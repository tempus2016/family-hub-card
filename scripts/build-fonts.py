#!/usr/bin/env python3
"""Embed the Latin subsets of Lora and Outfit into src/styles/fonts.js.

HACS serves exactly one file, so the fonts travel inside the bundle as data
URLs. Run after changing anything in assets/fonts/ and commit the output.
"""
import base64, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONTS = [("Lora", "lora.woff2", "400 700"), ("Outfit", "outfit.woff2", "300 800")]

faces = []
for family, file, weights in FONTS:
    data = base64.b64encode((ROOT / "assets" / "fonts" / file).read_bytes()).decode()
    faces.append(
        f"@font-face{{font-family:'{family}';font-style:normal;font-weight:{weights};"
        f"font-display:swap;src:url(data:font/woff2;base64,{data}) format('woff2')}}"
    )

out = ROOT / "src" / "styles" / "fonts.js"
out.write_text(
    "// Generated by scripts/build-fonts.py — do not edit. Lora and Outfit, SIL OFL 1.1,\n"
    "// Latin subsets. Licences in assets/fonts/.\n"
    "export const FONT_FACES = " + repr("".join(faces)).replace("'", '"', 1)[:-1] + '";\n'
    if False else
    "// Generated by scripts/build-fonts.py — do not edit. Lora and Outfit, SIL OFL 1.1,\n"
    "// Latin subsets. Licences in assets/fonts/.\n"
    "export const FONT_FACES = `" + "".join(faces) + "`;\n"
)
print(out, out.stat().st_size)
